package clase08_POO.modifacodres_acceso;

public class Person {
    // Atributos
    private String name;
    private int age;

    // Metodos de acceso
    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
