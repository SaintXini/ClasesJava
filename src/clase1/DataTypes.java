package clase1;

public class DataTypes {
    public static void main(String[] args) {

        //Tipos de datos Primitivos - basicos
        // en si se podría decir que son el nucle del lenguaje
        //float, long, byte
        int myInt = 37;
        System.out.println("My Int = " + myInt);

        double myDouble = 37.5;
        System.out.println("My Double = " + myDouble);

        // es un uso de caracteres y va con comillas simples
        char myChar = 'a';
        System.out.println("My Char = " + myChar);

        // Verdadero o falso
        boolean myBool = true;
        System.out.println("My Bool = " + myBool);

    }
}
